// An original mathematical landscape, drawn as projected level curves.
const ns = 'http://www.w3.org/2000/svg';
function project(x, y) {
  const z = 0.85 * Math.exp(-((x - 0.9) ** 2 + (y - 0.5) ** 2) / 1.35)
    - 0.53 * Math.exp(-((x + 0.7) ** 2 + (y + 0.3) ** 2) / 1.2)
    + 0.14 * Math.sin(x * 1.7 + y);
  return [280 + x * 73 + y * 41, 253 + y * 33 - x * 15 - z * 118];
}
function curve(points, stroke, width, opacity, parent) {
  const el = document.createElementNS(ns, 'path');
  el.setAttribute('d', points.map(([x,y], i) => `${i ? 'L' : 'M'}${x.toFixed(2)},${y.toFixed(2)}`).join(' '));
  el.setAttribute('fill', 'none'); el.setAttribute('stroke', stroke);
  el.setAttribute('stroke-width', width); el.setAttribute('opacity', opacity);
  parent.append(el); return el;
}
